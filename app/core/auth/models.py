"""The `auth` schema: who can log in (ARCHITECTURE.md §8.2)."""

import datetime as dt
import uuid
from typing import Any

from sqlalchemy import CheckConstraint, DateTime, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base


class UserRow(Base):
    __tablename__ = "users"
    __table_args__ = (
        # Emails are stored lower-cased, so "Anna@x.cz" and "anna@x.cz" are one account.
        CheckConstraint("email = lower(email)", name="email_lowercase"),
        {"schema": "auth"},
    )

    # Generated by Postgres; it comes back with the INSERT (RETURNING), like created_at.
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=func.gen_random_uuid())
    email: Mapped[str] = mapped_column(Text, unique=True)
    password_hash: Mapped[str] = mapped_column(Text)
    # Units, language, home place: validated by a Pydantic model from Phase 9.2.
    preferences: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'"))
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
